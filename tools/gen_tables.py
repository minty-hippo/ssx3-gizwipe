"""Extract the Gizmondo SSX 3 fixed-point trig tables from ssx_3.exe -> ds_runtime/source/sxtab.h
   sine: VA 0x8ef48, 2048 x i32 (16384 = 1.0, cos = index + 0x200)
   atan: VA 0xa0f48, 1025 x u16 (index = min*1024/max, value 0..0x200 in 12-bit 'half angle' units used by 0x8538c)"""
import struct, sys, os
if len(sys.argv) < 3: raise SystemExit('usage: gen_tables.py <ssx_3.exe> <out/sxtab.h>  (anim_ids.h, grabs.h, trick_str.h beside it)')
exe, out = sys.argv[1], sys.argv[2]
d = open(exe, 'rb').read()
def va(a):  # .rdata VA 0x87000 -> file 0x75e00
    return a - 0x87000 + 0x75e00
sin = struct.unpack_from('<2048i', d, va(0x8ef48))
at = struct.unpack_from('<1025H', d, va(0xa0f48))
assert sin[0] == 0 and sin[0x200] == 16384, sin[:4]
with open(out, 'w') as f:
    f.write('// generated by tools/gen_tables.py from ssx_3.exe (Gizmondo) - do not edit\n#pragma once\n#include <nds.h>\n')
    f.write('static const s16 sx_sin[2048] = {\n')
    for i in range(0, 2048, 16): f.write('  ' + ','.join(str(v) for v in sin[i:i+16]) + ',\n')
    f.write('};\nstatic const u16 sx_atan[1025] = {\n')
    for i in range(0, 1025, 16): f.write('  ' + ','.join(str(v) for v in at[i:i+16]) + ',\n')
    f.write('};\n')
print('ok', sin[:3], at[:4], at[1020:])

# animation id -> clip name table (VA 0xa96a8, 191 entries; ids index it directly; names truncated to 23 chars
# to match anims.ssxa)
def va_any(a):
    return a - 0xb1000 + 0x9fa00 if a >= 0xb1000 else a - 0x87000 + 0x75e00
names = []
for i in range(191):
    p = struct.unpack_from('<I', d, va_any(0xa96a8) + 4 * i)[0]
    if p == 0: names.append(''); continue
    o = va_any(p); s = d[o:d.index(b'\0', o)].decode('latin1')
    names.append(s[:-4][:23] if s.endswith('.xga') else '')
out2 = os.path.join(os.path.dirname(out), 'anim_ids.h')
with open(out2, 'w') as f:
    f.write('// generated by tools/gen_tables.py from ssx_3.exe - animation ids used by the rider code\n#pragma once\n')
    f.write(f'#define NANIM_IDS {len(names)}\nstatic const char *const ANIM_NAME[NANIM_IDS] = {{\n')
    for i, n in enumerate(names): f.write(f'  /* {i:3d} */ "{n}",\n')
    f.write('};\n')
print('anim ids', len(names), names[8], names[37], names[181], names[190])

# per-character grab tables (0x3af34 copies 15 x 0x30 bytes from 0xa6b60 + char*0x2d0) and the button combos (0xa6a70)
# character index order of the exe (mesh pointer table at file 0x9f048)
CHARS = ['zoe', 'moby', 'psymon', 'griff', 'viggo', 'elise', 'nate', 'mac', 'alegra', 'kaori']
with open(os.path.join(os.path.dirname(out), 'grabs.h'), 'w') as f:
    f.write('// generated by tools/gen_tables.py from ssx_3.exe - grab tricks\n#pragma once\n#include <nds.h>\n')
    f.write('typedef struct { u8 grab, tweak, uber[3], combo; u16 name, tname, uname[3]; } GrabDef;   // names: string ids (0xa9c28, see trick_str.h)\n')
    f.write('static const char *const GRAB_CHARS[10] = { ' + ', '.join(f'"{c}"' for c in CHARS) + ' };\n')
    f.write('static const u16 GRAB_COMBO[15][4] = {\n')
    for i in range(15):
        f.write('  { ' + ', '.join(f'0x{v:x}' for v in struct.unpack_from('<4I', d, va(0xa6a70) + 16 * i)) + ' },\n')
    f.write('};\nstatic const GrabDef GRABS[10][15] = {\n')
    for c in range(10):
        f.write(f'  {{ // {CHARS[c]}\n')
        for i in range(15):
            v = struct.unpack_from('<12i', d, va(0xa6b60 + c * 0x2d0) + 0x30 * i)
            f.write(f'    {{ {v[0]}, {v[1]}, {{ {v[2]}, {v[3]}, {v[4]} }}, {v[5]}, {v[6]}, {v[7]}, {{ {v[8]}, {v[9]}, {v[10]} }} }},\n')
        f.write('  },\n')
    f.write('};\n')
print('grabs.h written')

# English trick-name strings: the exe's string table (VA 0xa9c28, 5 languages per id; English first), ids 1155..1260
def _str(v):
    for lo, hi, diff in ((0x87000, 0xb0b96, 0x11200), (0xb1000, 0xa00000, 0x11600)):
        if lo <= v < hi:
            fo = v - diff; return d[fo:d.index(b'\0', fo)].decode('latin1')
    return ''
with open(os.path.join(os.path.dirname(out), 'trick_str.h'), 'w') as f:
    f.write('// generated by tools/gen_tables.py from ssx_3.exe - trick name strings (table 0xa9c28, English)\n#pragma once\n')
    f.write('#define TRICK_STR_FIRST 1155\n#define TRICK_STR_N 106\nstatic const char *const TRICK_STR[TRICK_STR_N] = {\n')
    for i in range(1155, 1261):
        sv = _str(struct.unpack_from('<I', d, va(0xa9c28) + i * 20)[0]).replace('\\', '\\\\').replace('"', '\\"')
        f.write(f'  /* {i} */ "{sv}",\n')
    f.write('};\n')
print('trick_str.h written')
