"""SSX 3 GizWipe: the game's own English texts that the DS source shows (menu help, event and attribute
descriptions, rider profiles ...), read from your ssx_3.exe at build time so that none of them is kept in this
repository. tools/xtext.txt lists each text by where it sits in the exe (id, file offset, length, a hash to check
it); the source writes XT_<id> where the text goes.

usage: python3 tools/gen_text.py <ssx_3.exe> <out/xtext.h>
"""
import hashlib, os, sys


def c_escape(b):
    out = []
    for c in b:
        ch = chr(c)
        if ch == '\\': out.append('\\\\')
        elif ch == '"': out.append('\\"')
        elif ch == '\n': out.append('\\n')
        elif 32 <= c < 127: out.append(ch)
        else: out.append('\\%03o' % c)
    return ''.join(out)


def main(exe, out):
    d = open(exe, 'rb').read()
    lines = ['// generated by tools/gen_text.py from ssx_3.exe - do not edit, do not commit', '#pragma once']
    bad = 0
    for ln in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'xtext.txt')):
        ln = ln.split('#')[0].split()
        if not ln: continue
        i, off, n, h = ln[0], int(ln[1], 16), int(ln[2]), ln[3]
        b = d[off:off + n]
        if hashlib.sha1(b).hexdigest()[:10] != h: bad += 1; print('text', i, 'does not match: is this the Gizmondo ssx_3.exe?'); b = b'?'
        lines.append(f'#define XT_{i} "{c_escape(b)}"')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('xtext.h:', len(lines) - 2, 'texts' + (f', {bad} MISMATCHED' if bad else ''))
    if bad: sys.exit(1)


if __name__ == '__main__':
    if len(sys.argv) < 3: raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
